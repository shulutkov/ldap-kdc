// Package krb5conf renders the Kerberos client configuration for a realm this service serves.
//
// The configuration is derived from the same settings the service runs with, so the client and the
// KDC cannot disagree about the realm, the enctypes, the ticket lifetimes or the ports.
package krb5conf

import (
	"errors"
	"fmt"
	"net"
	"strconv"
	"strings"
	"time"

	"github.com/shulutkov/ldap-kdc/internal/config"
)

// Options say where the client reaches the service when the name server does not tell it.
type Options struct {
	// Host is the name or address clients use for the KDC and the password service. It is required
	// without the name server when the listeners bind to all addresses, and otherwise defaults to the
	// host the listener is bound to.
	Host string

	// Source names the configuration file the output was generated from, for the header.
	Source string
}

// Render returns the krb5.conf of the realm.
//
// With the name server enabled the client finds the KDC and the realm through the zone's records and
// needs no [realms] block: that is the configuration the service documents for its own zone. Without
// it, the KDC and the password service are named explicitly.
func Render(cfg *config.Config, opts Options) (string, error) {
	realm := cfg.Server.Realm
	if realm == "" {
		return "", errors.New("server.realm is not set")
	}
	if len(cfg.KDC.EncTypes) == 0 {
		return "", errors.New("kdc.enc_types is empty")
	}
	enc := strings.Join(cfg.KDC.EncTypes, " ")

	var b strings.Builder
	b.WriteString("# Kerberos client configuration for the realm " + realm + ", generated by ldap-kdc krb5conf")
	if opts.Source != "" {
		b.WriteString(" from " + opts.Source)
	}
	b.WriteString(".\n")
	if cfg.DNS.Enabled {
		b.WriteString("# The KDC and the realm come from the zone's records (SRV and TXT), so there is no [realms] block.\n")
	} else {
		b.WriteString("# The KDC and the password service are named below: the name server is not enabled.\n")
	}

	b.WriteString("[libdefaults]\n")
	b.WriteString("    default_realm = " + realm + "\n")
	if cfg.DNS.Enabled {
		b.WriteString("    dns_lookup_realm = true\n")
		b.WriteString("    dns_lookup_kdc = true\n")
	}
	b.WriteString("    ticket_lifetime = " + duration(cfg.KDC.MaxTicketLife) + "\n")
	b.WriteString("    renew_lifetime = " + duration(cfg.KDC.MaxRenewableLife) + "\n")
	b.WriteString("    forwardable = true\n")
	b.WriteString("    default_tkt_enctypes = " + enc + "\n")
	b.WriteString("    default_tgs_enctypes = " + enc + "\n")
	b.WriteString("    permitted_enctypes = " + enc + "\n")

	if !cfg.DNS.Enabled {
		kdc, err := endpoint(cfg.KDC.Listen, cfg.KDC.Enabled, "kdc.listen", opts.Host)
		if err != nil {
			return "", err
		}
		b.WriteString("\n[realms]\n")
		b.WriteString("    " + realm + " = {\n")
		b.WriteString("        kdc = " + kdc + "\n")
		if cfg.KPasswd.Enabled {
			pw, err := endpoint(cfg.KPasswd.Listen, true, "kpasswd.listen", opts.Host)
			if err != nil {
				return "", err
			}
			b.WriteString("        kpasswd_server = " + pw + "\n")
		}
		b.WriteString("    }\n")
	}

	domain := cfg.Server.Domain
	if domain == "" {
		domain = strings.ToLower(realm)
	}
	b.WriteString("\n[domain_realm]\n")
	b.WriteString("    ." + domain + " = " + realm + "\n")
	b.WriteString("    " + domain + " = " + realm + "\n")
	return b.String(), nil
}

// duration writes a lifetime in the form krb5.conf reads: whole hours as "Nh", otherwise minutes.
func duration(d time.Duration) string {
	if d%time.Hour == 0 {
		return fmt.Sprintf("%dh", d/time.Hour)
	}
	return fmt.Sprintf("%dm", d/time.Minute)
}

// endpoint is host:port for a listener. An unspecified bind address needs the host given explicitly.
func endpoint(listen string, enabled bool, name, host string) (string, error) {
	if !enabled {
		return "", fmt.Errorf("%s: the listener is disabled but the realm needs it", name)
	}
	h, p, err := net.SplitHostPort(listen)
	if err != nil {
		return "", fmt.Errorf("%s: %w", name, err)
	}
	if _, err := strconv.Atoi(p); err != nil {
		return "", fmt.Errorf("%s: port %q is not a number", name, p)
	}
	if host != "" {
		h = host
	}
	if h == "" || h == "0.0.0.0" || h == "::" {
		return "", fmt.Errorf("%s binds to all addresses: name the host clients reach with -host", name)
	}
	return net.JoinHostPort(h, p), nil
}
