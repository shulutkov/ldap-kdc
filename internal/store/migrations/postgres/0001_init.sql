-- Directory objects and Kerberos key material.
--
-- This is the PostgreSQL counterpart of sqlite/0001_init.sql: the same tables under the same names.
-- Timestamps stay Unix seconds in BIGINT, so the Go code reads and writes one representation on
-- both databases, and flags are real booleans, which SQLite's 0 and 1 stand in for there. A name
-- that SQLite compares without regard to case (COLLATE NOCASE) is CITEXT here, which is what keeps
-- "Alice" and "alice" one account without a lower() in every query.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        CITEXT  NOT NULL,
    gid_number  BIGINT NOT NULL,
    description TEXT    NOT NULL DEFAULT '',
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT NOT NULL
);

CREATE UNIQUE INDEX groups_name_idx ON groups (name);
CREATE UNIQUE INDEX groups_gid_idx ON groups (gid_number);

-- A group may include another group; membership is resolved transitively at read time.
CREATE TABLE group_includes (
    group_id     BIGINT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    included_gid BIGINT NOT NULL,
    PRIMARY KEY (group_id, included_gid)
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          CITEXT  NOT NULL,
    uid_number    BIGINT NOT NULL,
    primary_group BIGINT NOT NULL,
    given_name    TEXT    NOT NULL DEFAULT '',
    sn            TEXT    NOT NULL DEFAULT '',
    mail          TEXT    NOT NULL DEFAULT '',
    login_shell   TEXT    NOT NULL DEFAULT '',
    home_dir      TEXT    NOT NULL DEFAULT '',
    disabled      BOOLEAN NOT NULL DEFAULT FALSE,
    pass_bcrypt   TEXT    NOT NULL DEFAULT '',
    otp_secret    TEXT    NOT NULL DEFAULT '',
    created_at    BIGINT NOT NULL,
    updated_at    BIGINT NOT NULL
);

CREATE UNIQUE INDEX users_name_idx ON users (name);
CREATE UNIQUE INDEX users_uid_idx ON users (uid_number);

CREATE TABLE user_groups (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    gid_number BIGINT NOT NULL,
    PRIMARY KEY (user_id, gid_number)
);

CREATE TABLE user_ssh_keys (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    position BIGINT NOT NULL,
    key      TEXT    NOT NULL,
    PRIMARY KEY (user_id, position)
);

CREATE TABLE user_attrs (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name     TEXT    NOT NULL,
    position BIGINT NOT NULL,
    value    TEXT    NOT NULL,
    PRIMARY KEY (user_id, name, position)
);

CREATE TABLE user_app_passwords (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       TEXT    NOT NULL,
    hash       TEXT    NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX user_app_passwords_user_idx ON user_app_passwords (user_id);

-- Capabilities belong to either a user or a group; owner_kind says which table owner_id refers to.
CREATE TABLE capabilities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_kind TEXT    NOT NULL CHECK (owner_kind IN ('user', 'group')),
    owner_id   BIGINT NOT NULL,
    action     TEXT    NOT NULL,
    object     TEXT    NOT NULL
);

CREATE INDEX capabilities_owner_idx ON capabilities (owner_kind, owner_id);

CREATE TABLE principals (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  TEXT    NOT NULL,
    realm                 TEXT    NOT NULL,
    user_id               BIGINT REFERENCES users (id) ON DELETE CASCADE,
    kvno                  BIGINT NOT NULL DEFAULT 1,
    enabled               BOOLEAN NOT NULL DEFAULT TRUE,
    requires_preauth      BOOLEAN NOT NULL DEFAULT TRUE,
    allow_forwardable     BOOLEAN NOT NULL DEFAULT TRUE,
    allow_proxiable       BOOLEAN NOT NULL DEFAULT TRUE,
    allow_renewable       BOOLEAN NOT NULL DEFAULT TRUE,
    allow_postdate        BOOLEAN NOT NULL DEFAULT FALSE,
    ok_as_delegate        BOOLEAN NOT NULL DEFAULT FALSE,
    allow_tgt_based_auth  BOOLEAN NOT NULL DEFAULT FALSE,
    max_ticket_life       BIGINT NOT NULL DEFAULT 0,
    max_renewable_life    BIGINT NOT NULL DEFAULT 0,
    password_last_set     BIGINT,
    password_expires_at   BIGINT,
    expires_at            BIGINT,
    locked_until          BIGINT,
    fail_count            BIGINT NOT NULL DEFAULT 0,
    last_success          BIGINT,
    last_failure          BIGINT,
    created_at            BIGINT NOT NULL,
    updated_at            BIGINT NOT NULL
);

CREATE UNIQUE INDEX principals_name_idx ON principals (name, realm);
CREATE INDEX principals_user_idx ON principals (user_id);

-- Long-term keys. Several kvnos may coexist so that tickets issued under the previous key can
-- still be decrypted while services pick up the new one.
CREATE TABLE principal_keys (
    principal_id BIGINT NOT NULL REFERENCES principals (id) ON DELETE CASCADE,
    kvno         BIGINT NOT NULL,
    etype        BIGINT NOT NULL,
    position     BIGINT NOT NULL DEFAULT 0,
    key          BYTEA   NOT NULL,
    salt         TEXT    NOT NULL DEFAULT '',
    s2kparams    TEXT    NOT NULL DEFAULT '',
    created_at   BIGINT NOT NULL,
    PRIMARY KEY (principal_id, kvno, etype)
);

CREATE TABLE delegation_targets (
    principal_id BIGINT NOT NULL REFERENCES principals (id) ON DELETE CASCADE,
    target       TEXT    NOT NULL,
    PRIMARY KEY (principal_id, target)
);

CREATE TABLE trusts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remote_realm TEXT    NOT NULL,
    direction    TEXT    NOT NULL CHECK (direction IN ('outbound', 'inbound', 'bidirectional')),
    transitive   BOOLEAN NOT NULL DEFAULT TRUE,
    enabled      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   BIGINT NOT NULL,
    updated_at   BIGINT NOT NULL
);

CREATE UNIQUE INDEX trusts_realm_idx ON trusts (remote_realm);
